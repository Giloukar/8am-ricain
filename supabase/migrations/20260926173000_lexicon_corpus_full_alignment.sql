-- Complete production-aligned LexiMind corpus metadata and quality observability.
alter table public.lexicon add column if not exists native_score real;
alter table public.lexicon add column if not exists prevalence real;
alter table public.lexicon add column if not exists content_status text not null default 'ready'
 check (content_status in ('candidate','ready','hidden'));
alter table public.lexicon alter column definition drop not null;
create index if not exists lexicon_native_discovery_idx on public.lexicon(content_status,difficulty,native_score desc,frequency_rank);

create table if not exists public.lexicon_sources(
 key text primary key,title text not null,url text not null,license text not null,attribution text,updated_at timestamptz not null default now()
);
alter table public.lexicon_sources enable row level security;
drop policy if exists "public lexicon sources read" on public.lexicon_sources;
create policy "public lexicon sources read" on public.lexicon_sources for select using(true);

insert into public.lexicon_sources(key,title,url,license,attribution) values
