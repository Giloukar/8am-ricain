on conflict(key) do update set title=excluded.title,url=excluded.url,license=excluded.license,attribution=excluded.attribution,updated_at=now();

create table if not exists public.lexicon_import_runs(
 id bigint generated by default as identity primary key,
 source_key text not null references public.lexicon_sources(key),
 started_at timestamptz not null default now(),finished_at timestamptz,
 candidates integer not null default 0,ready integer not null default 0,rejected integer not null default 0,notes text
);
alter table public.lexicon_import_runs enable row level security;

create or replace function public.lexicon_quality()
returns jsonb language sql stable security invoker set search_path='' as $$
select jsonb_build_object('total',count(*),'ready',count(*) filter(where content_status='ready'),'candidates',count(*) filter(where content_status='candidate'),'hidden',count(*) filter(where content_status='hidden'),'advanced_ready',count(*) filter(where content_status='ready' and difficulty>=4),'missing_definition',count(*) filter(where content_status='ready' and nullif(btrim(definition),'') is null),'avg_native_score',round(coalesce(avg(native_score) filter(where native_score is not null),0)::numeric,1)) from public.lexicon $$;
grant execute on function public.lexicon_quality() to authenticated;
